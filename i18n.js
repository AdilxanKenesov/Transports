  uz: (n, place) => (place ? `${place}ga ${n} ta qatnov` : `${n} ta qatnov`),
  ru: (n, place) => {
    const m10 = n % 10, m100 = n % 100;
    const word = m10 === 1 && m100 !== 11 ? "рейс" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "рейса" : "рейсов";
    return place ? `${place}: ${n} ${word}` : `${n} ${word}`;
  },
  en: (n, place) => `${n} ${n === 1 ? "trip" : "trips"}${place ? ` to ${place}` : ""}`,
